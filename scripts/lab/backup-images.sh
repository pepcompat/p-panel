#!/usr/bin/env bash
# P6 lab: build + push the backup HELPER image (infra/backup/helper) and the scratch-DB image (postgres 16,
# re-pushed from its pinned Docker Hub digest) to the lab registry, write their DIGEST references (as pulled by
# lab-dind) to .lab/backup.env, and set backup.helperImage in the node agent configs
# (infra/lab/node/agent-config/node-{a,b}.yaml, rewritten in place so the read-only bind mounts see it).
# Restart the lab agents afterwards: the agent reads backup.helperImage at start.
# Requires the lab to be up (scripts/lab/up.sh). linux/arm64 only. Talks only to the local Docker daemon, the
# loopback-published lab registry and (for base images / the restic release) Docker Hub + GitHub.
# shellcheck source=scripts/lab/_common.sh
source "$(dirname "${BASH_SOURCE[0]}")/_common.sh"

PUSH_REG="127.0.0.1:55000"
PULL_REG="lab-registry:5000"
OUT="${REPO_ROOT}/.lab/backup.env"
PG_SRC="postgres:16.10-bookworm@sha256:38471f330eb885e04de130b768d6db4e10469e2311879c7e5c699f6d2d8a1c74"
ACCEPT='application/vnd.oci.image.index.v1+json,application/vnd.oci.image.manifest.v1+json,application/vnd.docker.distribution.manifest.list.v2+json,application/vnd.docker.distribution.manifest.v2+json'

curl -fsS "http://${PUSH_REG}/v2/" >/dev/null || { log "ERROR: lab registry not reachable on ${PUSH_REG} (run scripts/lab/up.sh)"; exit 1; }

digest_of() { # <repo> <tag>
  curl -fsSI -H "Accept: ${ACCEPT}" "http://${PUSH_REG}/v2/$1/manifests/$2" | tr -d '\r' |
    awk -F': ' 'tolower($1)=="docker-content-digest"{print $2}'
}

log "building infra/backup/helper (linux/arm64)"
docker build --quiet --platform linux/arm64 --provenance=false --sbom=false \
  -t "${PUSH_REG}/ppanel-backup/helper:lab" "${REPO_ROOT}/infra/backup/helper" >/dev/null
docker push --quiet "${PUSH_REG}/ppanel-backup/helper:lab" >/dev/null
HD="$(digest_of ppanel-backup/helper lab)"
[[ "${HD}" =~ ^sha256:[a-f0-9]{64}$ ]] || { log "ERROR: no helper digest"; exit 1; }
HELPER="${PULL_REG}/ppanel-backup/helper@${HD}"

log "pushing the scratch DB image (${PG_SRC%@*}, linux/arm64)"
docker pull --quiet --platform linux/arm64 "${PG_SRC}" >/dev/null
docker tag "${PG_SRC}" "${PUSH_REG}/ppanel-backup/postgres:16"
docker push --quiet "${PUSH_REG}/ppanel-backup/postgres:16" >/dev/null
PD="$(digest_of ppanel-backup/postgres 16)"
[[ "${PD}" =~ ^sha256:[a-f0-9]{64}$ ]] || { log "ERROR: no postgres digest"; exit 1; }
SCRATCH_PG="${PULL_REG}/ppanel-backup/postgres@${PD}"

tmp="$(mktemp "${OUT}.XXXX")"
cat >"${tmp}" <<ENV
# generated by scripts/lab/backup-images.sh at $(date -u +%Y-%m-%dT%H:%M:%SZ) — digest refs as pulled by lab-dind
PPANEL_LAB_BACKUP_HELPER_IMAGE=${HELPER}
PPANEL_LAB_BACKUP_SCRATCH_PG=${SCRATCH_PG}
# restic URLs: agents (append-only, per-server private repo) / maintenance identity (lab-backup-admin)
PPANEL_LAB_BACKUP_REPO_BASE=http://lab-backup:8000
PPANEL_BACKUP_ADMIN_URL=http://127.0.0.1:58001
PPANEL_BACKUP_S3_ENDPOINT=http://127.0.0.1:59000
PPANEL_BACKUP_S3_BUCKET=ppanel-offsite
ENV
mv "${tmp}" "${OUT}"

for n in a b; do
  f="${REPO_ROOT}/infra/lab/node/agent-config/node-${n}.yaml"
  new="$(sed -E "s#^(  helperImage: ).*(\# ppanel-lab:helperImage)\$#\\1'${HELPER}' \\2#" "${f}")"
  printf '%s\n' "${new}" >"${f}" # same inode: the running node's read-only bind mount sees the change
done
log "wrote ${OUT} and backup.helperImage in node-{a,b}.yaml:"
cat "${OUT}"
log "restart the lab agents to pick up backup.helperImage"
