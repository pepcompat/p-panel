#!/usr/bin/env bash
# P4b lab: build deterministic bare git repos from infra/lab/git/<name>/<version>/ into .lab/git/<name>.git
# (one commit per version directory, sorted v1, v2, ...) and write .lab/git.env with
#   PPANEL_LAB_GIT_URL_<NAME>=git://lab-git/<name>.git
#   PPANEL_LAB_GIT_SHA_<NAME>=<40 hex>        (v1)
#   PPANEL_LAB_GIT_SHA_<NAME>_V2=<40 hex>     (v2, when present)
# Fixed author/committer/date + umask + no system/global git config => identical SHAs on every machine.
# lab-git (infra/compose/lab.yml) serves .lab/git read-only; new repos are visible without a restart.
# Local only: talks to no remote host. Safe to re-run (repos are rebuilt from scratch).
# shellcheck source=scripts/lab/_common.sh
source "$(dirname "${BASH_SOURCE[0]}")/_common.sh"

SRC="${REPO_ROOT}/infra/lab/git"
OUT_DIR="${REPO_ROOT}/.lab/git"
ENV_OUT="${REPO_ROOT}/.lab/git.env"
command -v git >/dev/null || { log "ERROR: git not installed"; exit 1; }
umask 022
mkdir -p "${OUT_DIR}"

export GIT_CONFIG_NOSYSTEM=1 GIT_CONFIG_GLOBAL=/dev/null
export GIT_AUTHOR_NAME="pPanel Lab" GIT_AUTHOR_EMAIL="lab@ppanel.invalid"
export GIT_COMMITTER_NAME="pPanel Lab" GIT_COMMITTER_EMAIL="lab@ppanel.invalid"
g() { git -c core.autocrlf=false -c core.fileMode=true -c init.defaultBranch=main -c commit.gpgSign=false "$@"; }

env_tmp="$(mktemp "${ENV_OUT}.XXXX")"
{
  echo "# generated by scripts/lab/git-fixtures.sh at $(date -u +%Y-%m-%dT%H:%M:%SZ) — lab only (git:// on the lab network)"
} >"${env_tmp}"

for repo_dir in "${SRC}"/*/; do
  name="$(basename "${repo_dir}")"
  [[ "${name}" =~ ^[a-z0-9][a-z0-9-]*$ ]] || continue
  key="$(echo "${name}" | tr 'a-z-' 'A-Z_')"
  work="$(mktemp -d)"
  g init -q "${work}"
  n=0
  for vdir in $(find "${repo_dir}" -mindepth 1 -maxdepth 1 -type d -name 'v[0-9]*' | sort -V); do
    v="$(basename "${vdir}")"
    n=$((n + 1))
    # replace the tree with this version's snapshot
    find "${work}" -mindepth 1 -maxdepth 1 ! -name .git -exec rm -rf {} +
    (cd "${vdir}" && tar cf - --exclude .DS_Store .) | (cd "${work}" && tar xf -)
    # deterministic modes: 0644 files, 0755 dirs (git only tracks the exec bit; none of the fixtures need it)
    find "${work}" -path "${work}/.git" -prune -o -type f -exec chmod 0644 {} +
    date="2026-01-0${n}T00:00:00Z"
    (cd "${work}" && g add -A && GIT_AUTHOR_DATE="${date}" GIT_COMMITTER_DATE="${date}" g commit -q -m "${name} ${v}")
    sha="$(g -C "${work}" rev-parse HEAD)"
    if [[ "${v}" == "v1" ]]; then
      echo "PPANEL_LAB_GIT_SHA_${key}=${sha}" >>"${env_tmp}"
    else
      echo "PPANEL_LAB_GIT_SHA_${key}_$(echo "${v}" | tr 'a-z' 'A-Z')=${sha}" >>"${env_tmp}"
    fi
    log "${name} ${v} -> ${sha}"
  done
  echo "PPANEL_LAB_GIT_URL_${key}=git://lab-git/${name}.git" >>"${env_tmp}"
  rm -rf "${OUT_DIR}/${name}.git.tmp"
  g clone -q --bare "${work}" "${OUT_DIR}/${name}.git.tmp"
  # protocol v2 serves any reachable commit; keep the export marker for non --export-all daemons
  touch "${OUT_DIR}/${name}.git.tmp/git-daemon-export-ok"
  rm -rf "${OUT_DIR}/${name}.git"
  mv "${OUT_DIR}/${name}.git.tmp" "${OUT_DIR}/${name}.git"
  chmod -R a+rX "${OUT_DIR}/${name}.git"
  rm -rf "${work}"
done
mv "${env_tmp}" "${ENV_OUT}"
log "wrote ${ENV_OUT}:"
cat "${ENV_OUT}"
