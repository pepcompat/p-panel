#!/usr/bin/env bash
# P4 lab: build the test images (infra/lab/images/*), push them to the lab registry on
# 127.0.0.1:55000 and write their DIGEST references (as seen from lab-dind) to .lab/images.env.
# Requires the lab to be up (scripts/lab/up.sh). linux/arm64 only (this Mac); no multi-arch.
# Talks only to the local Docker daemon and the loopback-published lab registry.
# shellcheck source=scripts/lab/_common.sh
source "$(dirname "${BASH_SOURCE[0]}")/_common.sh"

PUSH_REG="127.0.0.1:55000"   # Mac -> registry (loopback only)
PULL_REG="lab-registry:5000" # lab-dind -> registry (lab network)
OUT="${REPO_ROOT}/.lab/images.env"
IMAGES_DIR="${REPO_ROOT}/infra/lab/images"
mkdir -p "${REPO_ROOT}/.lab"

if ! curl -fsS "http://${PUSH_REG}/v2/" >/dev/null; then
  log "ERROR: lab registry not reachable on ${PUSH_REG} (run scripts/lab/up.sh)"; exit 1
fi

ACCEPT='application/vnd.oci.image.index.v1+json,application/vnd.oci.image.manifest.v1+json,application/vnd.docker.distribution.manifest.list.v2+json,application/vnd.docker.distribution.manifest.v2+json'

# build_push <name> <tag> [build-arg...]  -> prints the pull digest reference
build_push() {
  local name="$1" tag="$2"; shift 2
  local ref="${PUSH_REG}/ppanel-test/${name}:${tag}"
  local args=()
  for a in "$@"; do args+=(--build-arg "$a"); done
  docker build --quiet --platform linux/arm64 --provenance=false --sbom=false \
    ${args[@]+"${args[@]}"} -t "${ref}" "${IMAGES_DIR}/${name}" >/dev/null
  docker push --quiet "${ref}" >/dev/null
  local digest
  digest="$(curl -fsSI -H "Accept: ${ACCEPT}" "http://${PUSH_REG}/v2/ppanel-test/${name}/manifests/${tag}" |
    tr -d '\r' | awk -F': ' 'tolower($1)=="docker-content-digest"{print $2}')"
  [[ "${digest}" =~ ^sha256:[a-f0-9]{64}$ ]] || { log "ERROR: no digest for ${ref}"; exit 1; }
  echo "${PULL_REG}/ppanel-test/${name}@${digest}"
}

log "building + pushing test images to ${PUSH_REG}/ppanel-test/*"
WEB_V1="$(build_push web v1 VERSION=v1)"
WEB_V2="$(build_push web v2 VERSION=v2)"
BROKEN="$(build_push broken v1)"
ENVECHO="$(build_push envecho v1)"

tmp="$(mktemp "${OUT}.XXXX")"
cat >"${tmp}" <<ENV
# generated by scripts/lab/images.sh at $(date -u +%Y-%m-%dT%H:%M:%SZ) — digest refs as pulled by lab-dind
PPANEL_LAB_IMAGE_WEB_V1=${WEB_V1}
PPANEL_LAB_IMAGE_WEB_V2=${WEB_V2}
PPANEL_LAB_IMAGE_BROKEN=${BROKEN}
PPANEL_LAB_IMAGE_ENVECHO=${ENVECHO}
ENV
mv "${tmp}" "${OUT}"
log "wrote ${OUT}:"
cat "${OUT}"
